// README.md is generated too, so the images, links and the plain-text fallback never drift apart.

const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
export const projectFile = (repo) =>
  `project-${repo.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}.svg`;

export function readme(cfg, data) {
  const repoUrl = (name) => data.repos[name].url;

  const buttons = cfg.links
    .map((l) => `<a href="${attr(l.url)}"><img src="assets/btn-${l.id}.svg" height="42" alt="${attr(l.label)}"></a>`)
    .join('\n  ');

  const rows = [];
  for (let i = 0; i < cfg.projects.length; i += 2) {
    rows.push(
      cfg.projects
        .slice(i, i + 2)
        .map(
          (p) =>
            `<a href="${attr(repoUrl(p.repo))}"><img src="assets/${projectFile(p.repo)}" width="49%" alt="${attr(`${p.title}: ${p.desc}`)}"></a>`,
        )
        .join('\n  '),
    );
  }

  return `<!-- Generated by scripts/build.mjs. Edit scripts/config.mjs and rebuild instead of editing this file. -->

<div align="center">
  <img src="assets/hero.svg" width="100%" alt="${attr(`${cfg.name}. ${cfg.roles.join(' · ')}. ${cfg.tagline}`)}">
</div>

<p align="center">
  ${buttons}
</p>

<img src="assets/focus.svg" width="100%" alt="${attr(`What I build. ${cfg.focus.map((f) => `${f.title}: ${f.points.join(', ')}`).join('. ')}.`)}">

<img src="assets/stack.svg" width="100%" alt="${attr(`Tech stack. ${cfg.stack.map((r) => `${r.label}: ${r.items.map((i) => i.name).join(', ')}`).join('. ')}.`)}">

<img src="assets/projects.svg" width="100%" alt="Featured projects">

${rows.map((r) => `<p align="center">\n  ${r}\n</p>`).join('\n\n')}

<img src="assets/stats.svg" width="100%" alt="${attr(`GitHub activity: ${data.contributions} contributions in the last 12 months, ${data.activeDays} active days, longest streak ${data.longestStreak} days, ${data.stars} stars earned.`)}">

<img src="assets/footer.svg" width="100%" alt="${attr(cfg.motto)}">

<details>
<summary>Plain-text version</summary>

### ${cfg.name}

${cfg.roles.join(' · ')}

${cfg.tagline}

**What I build**

${cfg.focus.map((f) => `- **${f.title}**: ${f.points.join(', ')}`).join('\n')}

**Tech stack**

${cfg.stack.map((r) => `- **${r.label}**: ${r.items.map((i) => i.name).join(', ')}`).join('\n')}

**Featured projects**

${cfg.projects.map((p) => `- [${p.title}](${repoUrl(p.repo)}): ${p.desc}`).join('\n')}

**Links**

${cfg.links.map((l) => `- [${l.label}](${l.url})`).join('\n')}

</details>

<p align="center">
  <img src="https://komarev.com/ghpvc/?username=${cfg.login}&label=profile%20views&color=7c3aed&style=flat-square" alt="Profile views">
  <br>
  <sub>This page rebuilds itself every day from <a href="scripts/config.mjs">one config file</a>.</sub>
</p>
`;
}
